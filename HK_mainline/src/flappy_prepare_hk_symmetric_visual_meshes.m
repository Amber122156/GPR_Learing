function flappy_prepare_hk_symmetric_visual_meshes(projectRoot)
%FLAPPY_PREPARE_HK_SYMMETRIC_VISUAL_MESHES Build visual-only symmetric STL set.
%
% The current STL files are the coordinate authority.  The right-side CAD
% components are intentionally not used because a symmetric flapper is built
% by reflecting the supplied left-side geometry about the torso XZ mid-plane.
%
% All source and output STL coordinates are millimetres.  This routine changes
% only vertices/normals in display meshes; it never changes model joints,
% masses, inertias, or aerodynamic parameters.

arguments
    projectRoot (1,1) string
end

sourceRoot = fullfile(projectRoot,"CAD");
outputRoot = fullfile(projectRoot,"assets","HK_prototype","meshes");
p = flappy_parameters(projectRoot);
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end

frameSource = fullfile(sourceRoot,"frame.STL");
leftLeadingEdgeSource = fullfile(sourceRoot,"left_wing_LE.STL");
leftWingSource = fullfile(sourceRoot,"left_wing.STL");
assert(isfile(frameSource) && isfile(leftLeadingEdgeSource) && isfile(leftWingSource), ...
    "Expected frame.STL, left_wing_LE.STL, and left_wing.STL in %s.",sourceRoot);

% Current frozen Flappy link frames at zero stroke/rotate angle [mm].
modelLeftRoot = localPose([0; 15; 20], [1; 0; 0], [0; 0; 1]);
modelRightRoot = localPose([0; -15; 20], [1; 0; 0], [0; 0; 1]);

% The updated left-side STL coordinates use +Y for span and +Z for chord.
% Flappy uses +Y for the left span and -Z for chord, hence Ry(pi).  The same
% rotation applies to the leading edge and the wing surface.
%
% Visual hinge-registration offsets [mm], expressed AFTER this rotation in
% the Flappy left-link frame.  Keep them at zero when the STL origin is at
% the respective hinge.  Adjust LE and wing independently; the right-side
% values are generated by symmetry and must not be edited separately.
leftLeadingEdgeOffsetMm = [0; 0; 0]; % stroke hinge -> CAD LE hinge
% User-selected visual placement of the CAD wing surface.  This is separate
% from the physical pitch-axis offset configured in flappy_parameters.m.
leftWingOffsetMm = [0; 0; 0]; % rotate hinge -> CAD wing reference

flappyLeftRotation = [-1 0 0; 0 1 0; 0 0 -1];
leftLeadingEdgeTransform = localRigidTransform(flappyLeftRotation, ...
    leftLeadingEdgeOffsetMm);
leftWingTransform = localRigidTransform(flappyLeftRotation, ...
    leftWingOffsetMm);

% frame.STL is exported with all coordinates positive.  Its upper planform
% centre is the visual wing-root datum: [73.6396,73.6396,100] mm maps to the
% existing Flappy root height, z=18.9913 mm.  This is visual-only and leaves
% the torso link, its mass, and its inertia unchanged.
frameVisualOffsetMm = 1e3*p.vehicle.hk_frame_visual_offset_m;
frameDatumTransform = [-73.6396114; -73.6396114; -81.0087];
bodyMeshTransform = localTranslation(frameDatumTransform + frameVisualOffsetMm);

% Reflection about the torso XZ plane.  The transform is intentionally
% improper (det=-1); localWriteBinaryStl reverses triangle winding for it.
mirrorBodyMidplane = diag([1 -1 1 1]);
rightLeadingEdgeTransform = inv(modelRightRoot) * mirrorBodyMidplane * ...
    modelLeftRoot * leftLeadingEdgeTransform;
rightWingTransform = inv(modelRightRoot) * mirrorBodyMidplane * ...
    modelLeftRoot * leftWingTransform;

localWriteBinaryStl(frameSource,fullfile(outputRoot,"torso_symmetric_visual.STL"),bodyMeshTransform);
localWriteBinaryStl(leftLeadingEdgeSource,fullfile(outputRoot,"left_LE_symmetric_visual.STL"),leftLeadingEdgeTransform);
localWriteBinaryStl(leftWingSource,fullfile(outputRoot,"left_wing_symmetric_visual.STL"),leftWingTransform);
localWriteBinaryStl(leftLeadingEdgeSource,fullfile(outputRoot,"right_LE_symmetric_visual.STL"),rightLeadingEdgeTransform);
localWriteBinaryStl(leftWingSource,fullfile(outputRoot,"right_wing_symmetric_visual.STL"),rightWingTransform);
end

function T = localPose(originMm,xAxis,zAxis)
xAxis = xAxis / norm(xAxis);
zAxis = zAxis / norm(zAxis);
yAxis = cross(zAxis,xAxis);
yAxis = yAxis / norm(yAxis);
% Re-orthogonalize X to protect against rounded STEP directions.
xAxis = cross(yAxis,zAxis);
xAxis = xAxis / norm(xAxis);
T = eye(4);
T(1:3,1:3) = [xAxis yAxis zAxis];
T(1:3,4) = originMm;
end

function T = localRigidTransform(rotation,translationMm)
T = eye(4);
T(1:3,1:3) = rotation;
T(1:3,4) = translationMm;
end

function T = localTranslation(translationMm)
T = eye(4);
T(1:3,4) = translationMm;
end

function localWriteBinaryStl(sourceFile,targetFile,transform)
sourceId = fopen(sourceFile,"rb");
assert(sourceId >= 0,"Could not read %s",sourceFile);
sourceCleanup = onCleanup(@() fclose(sourceId));
header = fread(sourceId,80,"*uint8");
triangleCount = fread(sourceId,1,"*uint32");
assert(~isempty(triangleCount),"Invalid binary STL header: %s",sourceFile);

targetId = fopen(targetFile,"wb");
assert(targetId >= 0,"Could not create %s",targetFile);
targetCleanup = onCleanup(@() fclose(targetId));
fwrite(targetId,header,"uint8");
fwrite(targetId,triangleCount,"uint32");

rotation = transform(1:3,1:3);
translation = transform(1:3,4);
isReflection = det(rotation) < 0;
for triangleIndex = 1:double(triangleCount)
    normal = fread(sourceId,3,"*single");
    vertices = fread(sourceId,9,"*single");
    attribute = fread(sourceId,1,"*uint16");
    assert(numel(normal)==3 && numel(vertices)==9 && ~isempty(attribute), ...
        "Truncated binary STL: %s",sourceFile);

    normal = rotation * double(normal);
    vertices = rotation * reshape(double(vertices),3,3) + translation;
    if isReflection
        vertices = vertices(:,[1 3 2]);
    end
    fwrite(targetId,single(normal),"single");
    fwrite(targetId,single(vertices(:)),"single");
    fwrite(targetId,attribute,"uint16");
end
end
